#!/usr/bin/env node
/**
 * Seed a disposable sample event into the LOCAL D1 database so contributors can
 * exercise the guest gallery — filters, captions, favorites, collections and
 * the media viewer — without a Cloudflare or Google account.
 *
 *   npm run sample:gallery        create or refresh the sample event
 *   npm run sample:gallery:reset  remove just the sample event
 *
 * This script can only write to local D1: it requires the explicit --local
 * flag, accepts no other wrangler flags, and always invokes wrangler with
 * --local against .wrangler/state. It needs no OAuth secrets; if .dev.vars is
 * missing it is created with throwaway local credentials and SAMPLE_MEDIA=1,
 * which lets the dev server serve generated media for "sample:" object keys
 * (see lib/sample-media.ts). The deployed Worker keeps streaming originals
 * from Google Drive.
 */
import { spawnSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const wrangler = join(root, "node_modules", "wrangler", "bin", "wrangler.js");
const config = join(root, "wrangler.json");
const persistTo = join(root, ".wrangler", "state");
const devVarsPath = join(root, ".dev.vars");

const ALBUM_ID = "sample-event";
const ACCESS_TOKEN = "sample-gallery-token";
const GUEST_USERNAME = "sample-guest";
const GUEST_PASSWORD = "sample-pass";

const args = process.argv.slice(2);

// Hard gate: only the explicit local flags are accepted. Anything that could
// target remote D1 (--remote, --env, --config, ...) or an unknown option is a
// fatal error, and wrangler is only ever invoked with --local below.
const ALLOWED_FLAGS = new Set(["--local", "--reset", "--help"]);
const rejected = args.filter((flag) => !ALLOWED_FLAGS.has(flag));
if (args.includes("--help")) {
  console.log("Usage: node scripts/sample-gallery.mjs --local [--reset]\n\nSeeds a disposable sample event into local D1 (.wrangler/state).");
  process.exit(0);
}
if (rejected.length > 0 || !args.includes("--local")) {
  console.error(
    `Refusing to run: sample gallery seeding is local-only.\n` +
      `  ${rejected.length > 0 ? `Unsupported argument(s): ${rejected.join(" ")}\n  ` : ""}` +
      `Run \`npm run sample:gallery\` (or \`npm run sample:gallery:reset\`). Remote D1 is never targeted.`,
  );
  process.exit(1);
}
const resetOnly = args.includes("--reset");

function runWrangler(wranglerArgs, description) {
  const result = spawnSync(process.execPath, [wrangler, ...wranglerArgs], {
    cwd: root,
    encoding: "utf8",
    timeout: 180_000,
    env: { ...process.env, CI: "true", WRANGLER_SEND_METRICS: "false" },
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`${description} failed (wrangler exited with ${result.status ?? "unknown status"})`);
  }
}

function ensureDevVars() {
  if (!existsSync(devVarsPath)) {
    const password = `local-${randomBytes(8).toString("hex")}`;
    writeFileSync(
      devVarsPath,
      [
        "# Local development values generated by `npm run sample:gallery`.",
        "# Safe to delete; nothing here is a real secret. Google Drive keys are",
        "# intentionally absent so local media stays synthetic.",
        "ADMIN_USERNAME=admin",
        `ADMIN_PASSWORD=${password}`,
        `SESSION_SECRET=${randomBytes(32).toString("hex")}`,
        "SAMPLE_MEDIA=1",
        "",
      ].join("\n"),
      { mode: 0o600, flag: "wx" },
    );
    console.log("Created .dev.vars with throwaway local sign-in values and SAMPLE_MEDIA=1.");
    return;
  }
  const current = readFileSync(devVarsPath, "utf8");
  const sampleMediaSetting = current.match(/^SAMPLE_MEDIA=(.*)$/m);
  if (!sampleMediaSetting) {
    writeFileSync(devVarsPath, `${current.trimEnd()}\nSAMPLE_MEDIA=1\n`);
    console.log("Added SAMPLE_MEDIA=1 to .dev.vars so generated sample media can be served locally.");
  } else if (!/^(1|true)$/i.test(sampleMediaSetting[1].trim())) {
    // SAMPLE_MEDIA=0 (or anything else) disables the generated media route, so
    // the seeded gallery would 404 — flip it back on in place.
    writeFileSync(devVarsPath, current.replace(/^SAMPLE_MEDIA=.*$/m, "SAMPLE_MEDIA=1"));
    console.log("Enabled SAMPLE_MEDIA in .dev.vars so the seeded media is served locally.");
  }
  if (!/^SESSION_SECRET=/m.test(current) || !/^ADMIN_USERNAME=/m.test(current) || !/^ADMIN_PASSWORD=/m.test(current)) {
    console.warn("Note: .dev.vars lacks ADMIN_USERNAME/ADMIN_PASSWORD/SESSION_SECRET — /admin sign-in will fail without them.");
  }
}

function guestPasswordHash() {
  // Matches hashGuestPassword(albumId, password) in lib/security.ts.
  return createHash("sha256").update(`${ALBUM_ID}:${GUEST_PASSWORD}`).digest("hex");
}

function seedSql() {
  const now = Date.now();
  const minute = 60_000;
  const collections = [
    ["sample-col-ceremony", "Ceremony", "Vows, rings and the walk back down the aisle"],
    ["sample-col-reception", "Reception", "Toasts, cake and the dance floor"],
    ["sample-col-candids", "Candids", "Everything that happened between poses"],
  ];
  const photos = [
    // id, objectKey, filename, type, caption, featured, collection, uploader, source, size, age-in-minutes
    ["sample-photo-01", "sample:photo:0", "first-dance.png", "image/png", "First dance under the fairy lights", 1, "sample-col-reception", "Host", "host", 51240, 1],
    ["sample-photo-02", "sample:photo:1", "vows-closeup.png", "image/png", "Exchanging vows at the altar", 0, "sample-col-ceremony", "Host", "host", 48730, 2],
    ["sample-photo-03", "sample:photo:2", "bouquet-toss.png", "image/png", "", 0, "sample-col-ceremony", "Priya", "guest", 43118, 3],
    ["sample-photo-04", "sample:photo:3", "cake-cutting.png", "image/png", "Three tiers, zero regrets", 0, "sample-col-reception", "Host", "host", 52907, 4],
    ["sample-photo-05", "sample:photo:4", "group-portrait.png", "image/png", "The whole crew in one frame", 0, "sample-col-candids", "Alex", "guest", 46681, 5],
    ["sample-photo-06", "sample:photo:5", "sparkler-exit.png", "image/png", "Sparkler send-off to end the night", 1, "sample-col-candids", "Host", "host", 50212, 6],
    ["sample-photo-07", "sample:photo:6", "table-details.png", "image/png", "", 0, null, "Priya", "guest", 41566, 7],
    ["sample-video-01", "sample:video:0", "ceremony-highlights.mp4", "video/mp4", "The ceremony in one short clip", 0, "sample-col-ceremony", "Host", "host", 1902, 8],
    ["sample-video-02", "sample:video:1", "dance-floor.mp4", "video/mp4", "Dance floor energy", 0, "sample-col-reception", "Sam", "guest", 1901, 9],
  ];
  const collectionRows = collections
    .map(([id, name, description], index) =>
      `('${id}', '${ALBUM_ID}', '${name}', '${description}', ${now - (index + 1) * minute})`)
    .join(",\n  ");
  const photoRows = photos
    .map(([id, objectKey, filename, type, caption, featured, collection, uploader, source, size, age]) =>
      `('${id}', '${ALBUM_ID}', '${objectKey}', '${filename}', '${type}', '${caption}', ${featured}, ` +
      `${collection === null ? "NULL" : `'${collection}'`}, 'approved', '${uploader}', '${source}', ${size}, ${now - age * minute})`)
    .join(",\n  ");
  return `DELETE FROM photos WHERE album_id = '${ALBUM_ID}';
DELETE FROM event_collections WHERE album_id = '${ALBUM_ID}';
DELETE FROM event_metrics WHERE event_id = '${ALBUM_ID}';
DELETE FROM albums WHERE id = '${ALBUM_ID}';
INSERT INTO albums (id, title, event_type, event_date, description, tagline, location, theme,
  expected_guests, status, access_mode, allow_guest_uploads, moderation_mode, downloads_enabled,
  event_slug, cover_photo_id, slideshow_playing, slideshow_position, slideshow_updated_at,
  access_token, guest_username, guest_password_hash, created_at)
VALUES ('${ALBUM_ID}', 'Sample Wedding Celebration', 'Wedding', '2026-06-14',
  'Disposable sample event for local guest-gallery work. Seeded by npm run sample:gallery. Every photo and video is generated locally, so nothing touches Google Drive.',
  'A local fixture for filters, captions, favorites and the media viewer',
  'Localhost', 'rose', 0, 'live', 'link', 0, 'manual', 1,
  'sample-gallery', 'sample-photo-01', 1, 0, 0,
  '${ACCESS_TOKEN}', '${GUEST_USERNAME}', '${guestPasswordHash()}', ${now});
INSERT INTO event_collections (id, album_id, name, description, created_at) VALUES
  ${collectionRows};
INSERT INTO photos (id, album_id, object_key, filename, content_type, caption, is_featured,
  collection_id, moderation_status, uploader_name, source, size, created_at) VALUES
  ${photoRows};
`;
}

function executeSql(sql, description) {
  const dir = mkdtempSync(join(tmpdir(), "snap-hub-sample-"));
  try {
    const file = join(dir, "seed.sql");
    // Run the deletes+inserts atomically so a failed seed/reset never leaves a
    // half-updated sample event behind.
    writeFileSync(file, `BEGIN TRANSACTION;\n${sql}\nCOMMIT;\n`);
    runWrangler(
      ["d1", "execute", "DB", "--local", "--config", config, "--persist-to", persistTo, "--file", file],
      description,
    );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

ensureDevVars();
console.log("Applying local D1 migrations (this never touches remote D1)...");
runWrangler(
  ["d1", "migrations", "apply", "DB", "--local", "--config", config, "--persist-to", persistTo],
  "Local migrations",
);

if (resetOnly) {
  executeSql(
    `DELETE FROM photos WHERE album_id = '${ALBUM_ID}';
DELETE FROM event_collections WHERE album_id = '${ALBUM_ID}';
DELETE FROM event_metrics WHERE event_id = '${ALBUM_ID}';
DELETE FROM albums WHERE id = '${ALBUM_ID}';
`,
    "Sample event removal",
  );
  console.log(`Removed the sample event (${ALBUM_ID}) from local D1. Other local data was left untouched.`);
  console.log("To wipe ALL local data instead, delete .wrangler/state and re-run npm run db:migrate:local.");
  process.exit(0);
}

executeSql(seedSql(), "Sample gallery seed");

console.log(`Sample gallery ready — seeded 1 live event with 7 photos + 2 videos across 3 collections.
  (also includes captions, 2 highlights, a cover photo and an uncategorized item)

  1. npm run dev          (or npm run start for the built Worker)
  2. Open http://127.0.0.1:5173/g/${ACCESS_TOKEN}
     Friendly URL: http://127.0.0.1:5173/e/sample-gallery

The event uses link access, so no guest sign-in is needed. Guest credentials
${GUEST_USERNAME} / ${GUEST_PASSWORD} work if you switch access_mode to 'password'
while testing. Guest uploads are disabled on purpose: the sample gallery is a
browse-only fixture, so reseeding or resetting can never mix in real uploads or
leave orphaned files behind in Google Drive.

Reset:  npm run sample:gallery:reset   (removes only the sample event)
        delete .wrangler/state         (wipes ALL local D1 data)`);
